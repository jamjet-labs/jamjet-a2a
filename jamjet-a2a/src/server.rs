//! A2A v1.0 server — Axum-based JSON-RPC router with SSE streaming.
//!
//! # Security model
//!
//! Without an [`Authenticator`] the server is **single-tenant**: any caller
//! that can reach it can list, read, cancel and subscribe to every task.
//! Only run it that way on loopback, or behind a proxy or layer that
//! authenticates callers and passes a [`Principal`] in the request
//! extensions (as [`federation_auth_layer`] does). [`A2aServer::start`]
//! binds to `127.0.0.1` by default and logs a warning when bound to any other
//! address without an authenticator.
//!
//! With an authenticator (see [`A2aServer::with_authenticator`]):
//!
//! - every JSON-RPC request is authenticated before its body is parsed;
//! - each new task is bound to the [`Principal::id`] that created it;
//! - `GetTask`, `ListTasks`, `CancelTask`, `SubscribeToTask` and follow-up
//!   messages only see the caller's own tasks. Another principal's task is
//!   reported as `TaskNotFoundError`, so its existence is not revealed.
//!
//! Task ids are always generated by the server. A message that carries a
//! `taskId` continues that task, and must name a task the caller can see.
//!
//! [`federation_auth_layer`]: https://docs.rs/jamjet-a2a/latest/jamjet_a2a/federation/fn.federation_auth_layer.html

