/// Fetch a task the caller may access.
///
/// A task bound to another owner is reported exactly like a missing one, so
/// a caller cannot probe for other principals' task ids.
async fn visible_task(
    store: &dyn TaskStore,
    task_id: &str,
    owner: Option<&str>,
) -> Result<Task, A2aError> {
    match store.get_record(task_id).await? {
        Some(rec) if rec.owner.as_deref() == owner => Ok(rec.task),
        _ => Err(A2aProtocolError::TaskNotFound {
            task_id: task_id.to_string(),
        }
        .into()),
    }
}

/// Parse the params of a request, or build the -32602 response.
fn parse_params<T: serde::de::DeserializeOwned>(
    rpc: &mut IncomingRpc,
) -> Result<T, Json<serde_json::Value>> {
    serde_json::from_value(std::mem::take(&mut rpc.params)).map_err(|e| {
        make_json_rpc_error_response(
            rpc.id.clone(),
            -32602,
            &format!("Invalid params: {e}"),
            None,
        )
    })
}

/// Add a follow-up message to an existing task the caller can see. A message
/// without a `contextId` gets the task's.
///
/// Fails with `TaskNotFoundError` if the task is missing or belongs to
/// someone else, with `UnsupportedOperationError` if it is in a terminal
/// state, and with invalid params if the message's `contextId` differs from
/// the task's.
async fn continue_task(
    state: &ServerState,
    rpc_id: &serde_json::Value,
    task: &Task,
    message: &Message,
) -> Result<Message, Json<serde_json::Value>> {
    if task.status.state.is_terminal() {
        return Err(make_error_response(
            rpc_id.clone(),
            A2aProtocolError::TaskTerminal {
                task_id: task.id.clone(),
            },
        ));
    }
    if message.context_id.is_some() && message.context_id != task.context_id {
        return Err(make_json_rpc_error_response(
            rpc_id.clone(),
            -32602,
            "Invalid params: message contextId does not match the task's contextId",
            None,
        ));
    }
    // A2A v1.0 3.4.3: with only a taskId, the context comes from the task.
    let mut message = message.clone();
    if message.context_id.is_none() {
        message.context_id = task.context_id.clone();
    }
    // The store re-checks the terminal state atomically with the append.
    state
        .store
        .append_message(&task.id, message.clone())
        .await
        .map_err(|e| make_error_response(rpc_id.clone(), e))?;
    Ok(message)
}

/// Build a new task in the `Submitted` state with a server-generated id.
///
/// The task keeps the message's `contextId`, or gets a new one if the
/// message has none, so follow-up messages can be checked against it.
fn new_task(
    message: &Message,
    metadata: Option<std::collections::HashMap<String, serde_json::Value>>,
) -> Task {
    Task {
        id: uuid::Uuid::new_v4().to_string(),
        context_id: Some(
            message
                .context_id
                .clone()
                .unwrap_or_else(|| uuid::Uuid::new_v4().to_string()),
        ),
        status: TaskStatus {
            state: TaskState::Submitted,
            message: None,
            timestamp: Some(chrono::Utc::now().to_rfc3339()),
        },
        artifacts: vec![],
        history: Some(vec![message.clone()]),
        metadata,
    }
}

/// Run the task handler in the background.
///
/// For a new task the handler only runs if the task can still move to
/// `Working` (it may have been canceled in the meantime). If the handler
/// fails, the task is marked `Failed` unless it is already terminal.
fn spawn_handler(state: &ServerState, task_id: String, message: Message, new_task: bool) {
    if state.handler.is_none() {
        return;
    }
    let handler = Arc::clone(&state.handler);
    let store = Arc::clone(&state.store);

    tokio::spawn(async move {
        if new_task {
            let working_status = TaskStatus {
                state: TaskState::Working,
                message: None,
                timestamp: Some(chrono::Utc::now().to_rfc3339()),
            };
            if let Err(e) = store.update_status(&task_id, working_status).await {
                debug!(task_id = %task_id, error = %e, "task did not start");
                return;
            }
        }

        // Run the handler in its own task so a panic is caught (as a
        // JoinError) and the task is marked failed instead of staying in
        // Working forever.
        let run = {
            let handler = Arc::clone(&handler);
            let store = Arc::clone(&store);
            let task_id = task_id.clone();
            tokio::spawn(async move {
                match &*handler {
                    Some(h) => h.handle(task_id, message, store).await,
                    None => Ok(()),
                }
            })
        };
        let failure = match run.await {
            Ok(Ok(())) => None,
            Ok(Err(e)) => {
                error!(task_id = %task_id, error = %e, "handler failed");
                Some(format!("Handler error: {e}"))
            }
            Err(e) => {
                error!(task_id = %task_id, error = %e, "handler panicked");
                Some("Handler error: the handler panicked".to_string())
            }
        };
        if let Some(text) = failure {
            let failed_status = TaskStatus {
                state: TaskState::Failed,
                message: Some(Message {
                    message_id: uuid::Uuid::new_v4().to_string(),
                    context_id: None,
                    task_id: Some(task_id.clone()),
                    role: Role::Agent,
                    parts: vec![Part {
                        content: PartContent::Text(text),
                        metadata: None,
                        filename: None,
                        media_type: None,
                    }],
                    metadata: None,
                    extensions: vec![],
                    reference_task_ids: vec![],
                }),
                timestamp: Some(chrono::Utc::now().to_rfc3339()),
            };
            // Refused if the task is already terminal; nothing to do then.
            store.update_status(&task_id, failed_status).await.ok();
        }
    });
}

