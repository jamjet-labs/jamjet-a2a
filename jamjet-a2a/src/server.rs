// ────────────────────────────────────────────────────────────────────────────
// TaskHandler trait
// ────────────────────────────────────────────────────────────────────────────

/// User-provided handler that processes an incoming message for a task.
///
/// Implementations are spawned in a background `tokio::spawn` and receive
/// an `Arc<dyn TaskStore>` to update status and add artifacts as they work.
/// Once the task reaches a terminal state the store refuses further changes,
/// so a handler should treat [`A2aProtocolError::TaskTerminal`] (for example
/// after the client canceled the task) as a signal to stop.
///
/// Tenancy stops at this trait. The handler is not told who the caller is,
/// and `TaskStore::get` ignores ownership. A handler that looks up other
/// tasks (for example `referenceTaskIds`) or keeps memory per `contextId`
/// must scope that itself: clients choose `contextId` values freely, so two
/// callers can send the same one.
#[async_trait::async_trait]
pub trait TaskHandler: Send + Sync {
    async fn handle(
        &self,
        task_id: String,
        message: Message,
        store: Arc<dyn TaskStore>,
    ) -> Result<(), A2aError>;
}

// ────────────────────────────────────────────────────────────────────────────
// Method names
// ────────────────────────────────────────────────────────────────────────────

/// Map a JSON-RPC method name to its A2A v1.0 name.
///
/// Accepts the v1.0 names and the v0.3 aliases the server still serves
/// (`message/send`, `tasks/get`, ...). Returns `None` for unknown methods.
/// Dispatch and scope checks both go through this function, so an alias
/// cannot be used to get around a scope that is configured for the v1.0
/// name.
pub fn canonical_method(method: &str) -> Option<&'static str> {
    Some(match method {
        "SendMessage" | "message/send" => "SendMessage",
        "SendStreamingMessage" | "message/stream" => "SendStreamingMessage",
        "GetTask" | "tasks/get" => "GetTask",
        "ListTasks" => "ListTasks",
        "CancelTask" | "tasks/cancel" => "CancelTask",
        "SubscribeToTask" | "tasks/resubscribe" => "SubscribeToTask",
        "GetExtendedAgentCard" => "GetExtendedAgentCard",
        "CreateTaskPushNotificationConfig" | "tasks/pushNotificationConfig/set" => {
            "CreateTaskPushNotificationConfig"
        }
        "GetTaskPushNotificationConfig" => "GetTaskPushNotificationConfig",
        "ListTaskPushNotificationConfigs" => "ListTaskPushNotificationConfigs",
        "DeleteTaskPushNotificationConfig" => "DeleteTaskPushNotificationConfig",
        _ => return None,
    })
}

