/// `GET /.well-known/agent-card.json`
async fn agent_card_handler(State(state): State<ServerState>) -> impl IntoResponse {
    let headers = [
        (axum::http::header::ACCESS_CONTROL_ALLOW_ORIGIN, "*"),
        (axum::http::header::CACHE_CONTROL, "no-cache"),
    ];
    (
        headers,
        Json(serde_json::to_value(state.card.as_ref()).unwrap_or(serde_json::json!({}))),
    )
}

/// Incoming JSON-RPC request parsed from the POST body.
/// We use a `Value` for params since each method has different params.
struct IncomingRpc {
    id: serde_json::Value,
    method: String,
    params: serde_json::Value,
}

/// Largest JSON-RPC request body the server reads (Axum's default limit).
const MAX_RPC_BODY_BYTES: usize = 2 * 1024 * 1024;

/// `POST /` — JSON-RPC 2.0 dispatcher.
///
/// Reads the raw body instead of using `Json<T>` so that we can return
/// proper JSON-RPC error responses for malformed JSON (-32700) and invalid
/// requests (-32600) instead of Axum's default HTTP 422.
async fn jsonrpc_handler(
    State(state): State<ServerState>,
    request: axum::extract::Request,
) -> axum::response::Response {
    let (parts, body) = request.into_parts();

    // Step 0: Authenticate before reading the body. With an authenticator
    // configured it decides; otherwise use a principal set by an outer layer
    // (e.g. federation_auth_layer), if any.
    let principal = match &state.authenticator {
        Some(auth) => match auth.authenticate(&parts.headers).await {
            Ok(p) => Some(p),
            Err(e) => {
                warn!(error = %e, "A2A request rejected: authentication failed");
                return crate::auth::unauthenticated_response();
            }
        },
        None => parts.extensions.get::<Principal>().cloned(),
    };
    if principal.as_ref().is_some_and(|p| p.id.is_empty()) {
        error!("A2A request rejected: principal has an empty id");
        return crate::auth::unauthenticated_response();
    }

    let body = match tokio::time::timeout(
        state.body_read_timeout,
        axum::body::to_bytes(body, MAX_RPC_BODY_BYTES),
    )
    .await
    {
        Ok(Ok(b)) => b,
        Ok(Err(_)) => return axum::http::StatusCode::PAYLOAD_TOO_LARGE.into_response(),
        Err(_) => return axum::http::StatusCode::REQUEST_TIMEOUT.into_response(),
    };

    // Step 1: Parse JSON from raw bytes.
    let body: serde_json::Value = match serde_json::from_slice(&body) {
        Ok(v) => v,
        Err(_) => {
            return Json(serde_json::json!({
                "jsonrpc": "2.0",
                "id": null,
                "error": {"code": -32700, "message": "Parse error"}
            }))
            .into_response();
        }
    };

    // Step 2: Validate jsonrpc field.
    let jsonrpc = body.get("jsonrpc").and_then(|v| v.as_str());
    if jsonrpc != Some("2.0") {
        let id = body.get("id").cloned().unwrap_or(serde_json::Value::Null);
        return Json(serde_json::json!({
            "jsonrpc": "2.0",
            "id": id,
            "error": {"code": -32600, "message": "Invalid Request"}
        }))
        .into_response();
    }

    // Step 3: Validate id field (must be string, number, or null per JSON-RPC 2.0).
    if let Some(id_val) = body.get("id") {
        match id_val {
            serde_json::Value::String(_)
            | serde_json::Value::Number(_)
            | serde_json::Value::Null => {} // valid
            _ => {
                return Json(serde_json::json!({
                    "jsonrpc": "2.0",
                    "id": null,
                    "error": {"code": -32600, "message": "Invalid Request"}
                }))
                .into_response();
            }
        }
    }

    // Step 4: Extract method.
    let method = match body.get("method").and_then(|v| v.as_str()) {
        Some(m) => m.to_string(),
        None => {
            let id = body.get("id").cloned().unwrap_or(serde_json::Value::Null);
            return Json(serde_json::json!({
                "jsonrpc": "2.0",
                "id": id,
                "error": {"code": -32600, "message": "Invalid Request"}
            }))
            .into_response();
        }
    };

    // Step 5: Extract id and params.
    let rpc_id = body.get("id").cloned().unwrap_or(serde_json::Value::Null);
    let params = body
        .get("params")
        .cloned()
        .unwrap_or(serde_json::Value::Null);

    // Step 6: Resolve the method (v1.0 name or v0.3 alias) and check that the
    // caller may use it.
    let Some(canonical) = canonical_method(&method) else {
        return make_json_rpc_error_response(rpc_id, -32601, "Method not found", None)
            .into_response();
    };
    if let (Some(auth), Some(p)) = (&state.authenticator, &principal) {
        if !auth.authorize(p, canonical) {
            warn!(principal = %p.id, method = canonical, "A2A request rejected: not authorized");
            return crate::auth::forbidden_response(rpc_id, canonical);
        }
    }

    let rpc = IncomingRpc {
        id: rpc_id,
        method: method.clone(),
        params,
    };
    let owner = principal.map(|p| p.id);

    debug!(method = %method, "incoming JSON-RPC request");

    match canonical {
        "SendMessage" => handle_send_message(state, rpc, owner).await,
        "GetTask" => handle_get_task(state, rpc, owner).await,
        "ListTasks" => handle_list_tasks(state, rpc, owner).await,
        "CancelTask" => handle_cancel_task(state, rpc, owner).await,
        "SendStreamingMessage" => handle_send_streaming(state, rpc, owner).await,
        "SubscribeToTask" => handle_subscribe(state, rpc, owner).await,
        "GetExtendedAgentCard" => handle_get_extended_card(state, rpc).await,
        _ => make_error_response(
            rpc.id,
            A2aProtocolError::UnsupportedOperation { method: rpc.method },
        )
        .into_response(),
    }
}

