async fn handle_send_message(
    state: ServerState,
    mut rpc: IncomingRpc,
    owner: Option<String>,
) -> axum::response::Response {
    let req: SendMessageRequest = match parse_params(&mut rpc) {
        Ok(r) => r,
        Err(resp) => return resp.into_response(),
    };
    let message = req.message.clone();

    let task_id = match message.task_id.as_deref() {
        // Follow-up: the task must exist, be visible to the caller and not
        // be terminal.
        Some(task_id) => {
            let task = match visible_task(&*state.store, task_id, owner.as_deref()).await {
                Ok(t) => t,
                Err(e) => return make_error_response(rpc.id, e).into_response(),
            };
            let message = match continue_task(&state, &rpc.id, &task, &message).await {
                Ok(m) => m,
                Err(resp) => return resp.into_response(),
            };
            spawn_handler(&state, task.id.clone(), message, false);
            task.id
        }
        // New task: the server picks the id.
        None => {
            let task = new_task(&message, req.metadata.clone());
            let task_id = task.id.clone();
            if let Err(e) = state.store.insert(task, owner).await {
                error!(error = %e, "failed to insert task");
                return make_error_response(rpc.id, e).into_response();
            }
            spawn_handler(&state, task_id.clone(), message, true);
            task_id
        }
    };

    // The handler runs in the background either way; return the current
    // snapshot. A2A v1.0: SendMessage returns {"result": {"task": <Task>}}
    match state.store.get(&task_id).await {
        Ok(Some(task)) => {
            make_success_response(rpc.id, &serde_json::json!({ "task": task })).into_response()
        }
        Ok(None) => {
            make_error_response(rpc.id, A2aProtocolError::TaskNotFound { task_id }).into_response()
        }
        Err(e) => make_error_response(rpc.id, e).into_response(),
    }
}

async fn handle_get_task(
    state: ServerState,
    mut rpc: IncomingRpc,
    owner: Option<String>,
) -> axum::response::Response {
    let req: GetTaskRequest = match parse_params(&mut rpc) {
        Ok(r) => r,
        Err(resp) => return resp.into_response(),
    };

    match visible_task(&*state.store, &req.id, owner.as_deref()).await {
        Ok(mut task) => {
            // Apply historyLength limiting.
            if let Some(hl) = req.history_length {
                if hl == 0 {
                    task.history = None;
                } else if let Some(ref mut hist) = task.history {
                    let hl = hl as usize;
                    if hist.len() > hl {
                        let start = hist.len() - hl;
                        *hist = hist.split_off(start);
                    }
                }
            }
            make_success_response(rpc.id, &task).into_response()
        }
        Err(e) => make_error_response(rpc.id, e).into_response(),
    }
}

async fn handle_list_tasks(
    state: ServerState,
    mut rpc: IncomingRpc,
    owner: Option<String>,
) -> axum::response::Response {
    let req: ListTasksRequest = match parse_params(&mut rpc) {
        Ok(r) => r,
        Err(resp) => return resp.into_response(),
    };

    // Validate page_size: must be 1..=100 if provided.
    if let Some(ps) = req.page_size {
        if ps <= 0 || ps > 100 {
            return make_json_rpc_error_response(
                rpc.id,
                -32602,
                "Invalid params: pageSize must be between 1 and 100",
                None,
            )
            .into_response();
        }
    }

    // Validate history_length: must be >= 0 if provided.
    if let Some(hl) = req.history_length {
        if hl < 0 {
            return make_json_rpc_error_response(
                rpc.id,
                -32602,
                "Invalid params: historyLength must be >= 0",
                None,
            )
            .into_response();
        }
    }

    // Validate page_token: if provided and non-empty, it must be the id of a
    // task the caller can see. Other owners' ids are treated as invalid, so
    // the token cannot be used to probe for them.
    if let Some(ref token) = req.page_token {
        if !token.is_empty() {
            match state.store.is_visible(token, owner.as_deref()).await {
                Ok(true) => {}
                Ok(false) => {
                    return make_json_rpc_error_response(
                        rpc.id,
                        -32602,
                        "Invalid params: invalid pageToken",
                        None,
                    )
                    .into_response();
                }
                Err(e) => return make_error_response(rpc.id, e).into_response(),
            }
        }
    }

    // Validate statusTimestampAfter: must be a valid ISO 8601 timestamp.
    if let Some(ref ts) = req.status_timestamp_after {
        if chrono::DateTime::parse_from_rfc3339(ts).is_err() {
            return make_json_rpc_error_response(
                rpc.id,
                -32602,
                "Invalid params: statusTimestampAfter must be a valid ISO 8601 timestamp",
                None,
            )
            .into_response();
        }
    }

    match state.store.list(&req, owner.as_deref()).await {
        Ok(mut resp) => {
            // Do not rely on a custom store's filtering alone: drop anything
            // that is not the caller's. If the store got it wrong, its
            // totalSize and nextPageToken cannot be trusted either.
            let listed = resp.tasks.len();
            let mut visible = Vec::with_capacity(listed);
            for task in resp.tasks {
                if matches!(
                    state.store.is_visible(&task.id, owner.as_deref()).await,
                    Ok(true)
                ) {
                    visible.push(task);
                } else {
                    error!(task_id = %task.id, "store listed a task the caller does not own");
                }
            }
            let token_ok = resp.next_page_token.is_empty()
                || matches!(
                    state
                        .store
                        .is_visible(&resp.next_page_token, owner.as_deref())
                        .await,
                    Ok(true)
                );
            if visible.len() != listed || !token_ok {
                resp.total_size = visible.len() as i32;
                resp.next_page_token = String::new();
            }
            resp.page_size = visible.len() as i32;
            resp.tasks = visible;
            make_success_response(rpc.id, &resp).into_response()
        }
        Err(e) => make_error_response(rpc.id, e).into_response(),
    }
}

async fn handle_cancel_task(
    state: ServerState,
    mut rpc: IncomingRpc,
    owner: Option<String>,
) -> axum::response::Response {
    let req: CancelTaskRequest = match parse_params(&mut rpc) {
        Ok(r) => r,
        Err(resp) => return resp.into_response(),
    };

    let task_id = req.id.clone();
    match state.store.is_visible(&task_id, owner.as_deref()).await {
        Ok(true) => {}
        Ok(false) => {
            return make_error_response(rpc.id, A2aProtocolError::TaskNotFound { task_id })
                .into_response()
        }
        Err(e) => return make_error_response(rpc.id, e).into_response(),
    }
    match state.store.cancel(&task_id).await {
        Ok(()) => {
            // Return the updated task.
            match state.store.get(&task_id).await {
                Ok(Some(task)) => make_success_response(rpc.id, &task).into_response(),
                Ok(None) => make_error_response(rpc.id, A2aProtocolError::TaskNotFound { task_id })
                    .into_response(),
                Err(e) => make_error_response(rpc.id, e).into_response(),
            }
        }
        Err(e) => make_error_response(rpc.id, e).into_response(),
    }
}

async fn handle_send_streaming(
    state: ServerState,
    mut rpc: IncomingRpc,
    owner: Option<String>,
) -> axum::response::Response {
    let req: SendMessageRequest = match parse_params(&mut rpc) {
        Ok(r) => r,
        Err(resp) => return resp.into_response(),
    };
    let Some(slot) = state.streams.acquire(&owner) else {
        return too_many_streams_response(rpc.id);
    };
    let message = req.message.clone();

    let (task_id, rx, message, new) = match message.task_id.as_deref() {
        // Follow-up: subscribe before appending, so that a terminal update
        // either lands on this stream or makes the append fail.
        Some(task_id) => {
            let task = match visible_task(&*state.store, task_id, owner.as_deref()).await {
                Ok(t) => t,
                Err(e) => return make_error_response(rpc.id, e).into_response(),
            };
            let Some(rx) = state.store.subscribe(&task.id).await else {
                return make_error_response(
                    rpc.id,
                    A2aProtocolError::TaskNotFound {
                        task_id: task.id.clone(),
                    },
                )
                .into_response();
            };
            let message = match continue_task(&state, &rpc.id, &task, &message).await {
                Ok(m) => m,
                Err(resp) => return resp.into_response(),
            };
            (task.id, rx, message, false)
        }
        // New task: the server picks the id. Nothing can update the task
        // until the handler is spawned, so subscribing after insert is safe.
        None => {
            let task = new_task(&message, req.metadata.clone());
            let task_id = task.id.clone();
            if let Err(e) = state.store.insert(task, owner).await {
                error!(error = %e, "failed to insert task");
                return make_error_response(rpc.id, e).into_response();
            }
            let Some(rx) = state.store.subscribe(&task_id).await else {
                return make_json_rpc_error_response(
                    rpc.id,
                    -32603,
                    "Failed to create event stream",
                    None,
                )
                .into_response();
            };
            (task_id, rx, message, true)
        }
    };

    // A2A 3.1.2: the stream starts with the Task. Take the snapshot before
    // the handler runs; later changes arrive on `rx`.
    let initial = match state.store.get(&task_id).await {
        Ok(Some(task)) => task,
        Ok(None) => {
            return make_error_response(rpc.id, A2aProtocolError::TaskNotFound { task_id })
                .into_response()
        }
        Err(e) => return make_error_response(rpc.id, e).into_response(),
    };
    spawn_handler(&state, task_id.clone(), message, new);
    let events = task_event_stream(
        rx,
        Arc::clone(&state.store),
        task_id,
        Some(initial),
        false,
        Some(slot),
    );
    make_sse_stream(events).into_response()
}

async fn handle_subscribe(
    state: ServerState,
    mut rpc: IncomingRpc,
    owner: Option<String>,
) -> axum::response::Response {
    let req: SubscribeToTaskRequest = match parse_params(&mut rpc) {
        Ok(r) => r,
        Err(resp) => return resp.into_response(),
    };

    if let Err(e) = visible_task(&*state.store, &req.id, owner.as_deref()).await {
        return make_error_response(rpc.id, e).into_response();
    }

    let Some(rx) = state.store.subscribe(&req.id).await else {
        return make_error_response(rpc.id, A2aProtocolError::TaskNotFound { task_id: req.id })
            .into_response();
    };

    // Check the state after subscribing: a terminal update that happens from
    // here on is delivered on `rx` and closes the stream; one that already
    // happened is caught here.
    match state.store.get(&req.id).await {
        Ok(Some(task)) if task.status.state.is_terminal() => {
            make_error_response(rpc.id, A2aProtocolError::TaskTerminal { task_id: req.id })
                .into_response()
        }
        Ok(Some(task)) => {
            let Some(slot) = state.streams.acquire(&owner) else {
                return too_many_streams_response(rpc.id);
            };
            // A2A 3.1.6: the stream starts with the current Task. A task that
            // is already waiting for input gets that one event and the
            // stream closes, the same rule as for a live update.
            let close_now = task.status.state.is_interrupted();
            let events = task_event_stream(
                rx,
                Arc::clone(&state.store),
                req.id,
                Some(task),
                close_now,
                Some(slot),
            );
            make_sse_stream(events).into_response()
        }
        Ok(None) => make_error_response(rpc.id, A2aProtocolError::TaskNotFound { task_id: req.id })
            .into_response(),
        Err(e) => make_error_response(rpc.id, e).into_response(),
    }
}

async fn handle_get_extended_card(
    state: ServerState,
    rpc: IncomingRpc,
) -> axum::response::Response {
    make_success_response(rpc.id, state.card.as_ref()).into_response()
}

