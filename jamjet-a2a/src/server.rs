fn make_success_response<T: serde::Serialize>(
    id: serde_json::Value,
    result: &T,
) -> Json<serde_json::Value> {
    Json(serde_json::json!({
        "jsonrpc": "2.0",
        "id": id,
        "result": result,
    }))
}

fn make_error_response(
    id: serde_json::Value,
    error: impl Into<A2aError>,
) -> Json<serde_json::Value> {
    let error: A2aError = error.into();
    match error {
        A2aError::Protocol(ref proto) => {
            make_json_rpc_error_response(id, proto.json_rpc_code(), &error.to_string(), None)
        }
        // Too many messages on one task is a problem with the request, not
        // a server fault.
        A2aError::Store(A2aStoreError::HistoryFull { .. }) => {
            make_json_rpc_error_response(id, -32602, &format!("Invalid params: {error}"), None)
        }
        _ => make_json_rpc_error_response(id, -32603, &error.to_string(), None),
    }
}

fn make_json_rpc_error_response(
    id: serde_json::Value,
    code: i32,
    message: &str,
    data: Option<serde_json::Value>,
) -> Json<serde_json::Value> {
    let mut error = serde_json::json!({
        "code": code,
        "message": message,
    });
    if let Some(d) = data {
        error["data"] = d;
    }
    Json(serde_json::json!({
        "jsonrpc": "2.0",
        "id": id,
        "error": error,
    }))
}

